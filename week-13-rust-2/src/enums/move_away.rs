
pub fn move_away(direction: String){
    if direction == "UP" {
        println!("Moved in the {} direction", direction);
    }
    else if direction == "DOWN" {
        println!("Moved in the {} direction", direction);
    }
    else if direction == "RIGHT" {
        println!("Moved in the {} direction", direction);
    }

    else if direction == "LEFT" {
        println!("Moved in the {} direction", direction);
    } else {
        print!("No direction!")
    }
}